/**
 * Loads or initializes the simulated Firebase Realtime Database node for the Top 100 CEOs.
 * Operates 100% offline via localStorage.
 */
export function getFirebaseRealtimeDbLeaderboard(): FirebaseRealtimeLeaderboardNode {
  if (typeof window !== 'undefined' && typeof window.localStorage !== 'undefined') {
    try {
      const raw = localStorage.getItem(REALTIME_DB_STORAGE_KEY);
      if (raw) {
        const parsed = JSON.parse(raw);
        if (parsed && parsed.entries && Object.keys(parsed.entries).length >= 90) {
          return parsed;
        }
      }
    } catch (e) {
      console.warn('Erro ao carregar banco offline:', e);
    }
  }

  // Build default seed dictionary
  const entries: Record<string, LeaderboardEntry> = {};
  OFFLINE_BRAZILIAN_CEOS_SEED.forEach((seed, index) => {
    entries[seed.id] = {
      ...seed,
      rank: index + 1,
      isPlayer: false,
      updatedAt: Date.now() - (index * 3600_000),
    };
  });

  const node: FirebaseRealtimeLeaderboardNode = {
    ref: RTDB_LEADERBOARD_PATH,
    syncedOffline: true,
    updatedAt: Date.now(),
    entries,
  };

  if (typeof window !== 'undefined' && typeof window.localStorage !== 'undefined') {
    try {
      localStorage.setItem(REALTIME_DB_STORAGE_KEY, JSON.stringify(node));
    } catch (e) {
      // ignore
    }
  }

  return node;
}

/**
 * Merges the current player's live net worth and profile into the Top 100 ranking,
 * calculating accurate positions, ranks, and distance to the next rival.
 */
export function computeTop100Leaderboard(gameState: GameState): {
  leaderboard: LeaderboardEntry[];
  playerEntry: LeaderboardEntry;
  playerRank: number;
  totalCeos: number;
  nextCeoToBeat: LeaderboardEntry | null;
  diffToNextRank: number;
  top10: LeaderboardEntry[];
} {
  const rtdb = getFirebaseRealtimeDbLeaderboard();
  const playerNetWorth = calculateNetWorth(gameState);
  const now = Date.now();

  const playerCeoName = gameState.ceoName && gameState.ceoName.trim().length > 0
    ? gameState.ceoName.trim()
    : 'Você (CEO)';
  const playerCompanyName = gameState.companyName && gameState.companyName.trim().length > 0
    ? gameState.companyName.trim()
    : 'Império Magnata';

  // Construct Player's Entry
  const playerEntry: LeaderboardEntry = {
    id: 'player_ceo_active',
    rank: 1, // Will be calculated after sort
    ceoName: `${playerCeoName}`,
    companyName: playerCompanyName,
    netWorth: Math.max(0, playerNetWorth),
    sector: 'Conglomerado Geral',
    city: 'São Paulo',
    state: 'SP',
    avatar: '⭐',
    avatarBg: '#10b981',
    isPlayer: true,
    biography: `Comandante supremo de ${playerCompanyName}. Prédio com ${gameState.skyscraperFloors} andares e ${gameState.employees.length} executivos.`,
    updatedAt: now,
  };

  // Convert offline dictionary to array and filter out any previous player entry
  const competitors: LeaderboardEntry[] = Object.values(rtdb.entries).filter((e) => !e.isPlayer);

  // Combine competitors + current live player
  const allEntries: LeaderboardEntry[] = [...competitors, playerEntry];

  // Sort descending by Net Worth (highest net worth = Rank 1)
  allEntries.sort((a, b) => b.netWorth - a.netWorth);

  // Assign ranks 1 to N
  let playerFoundRank = 100;
  allEntries.forEach((entry, index) => {
    entry.rank = index + 1;
    if (entry.isPlayer) {
      playerFoundRank = index + 1;
    }
  });

  // Keep exactly top 100 entries for leaderboard view
  // If player is rank 101+, ensure player is included at the end or in slice
  let top100: LeaderboardEntry[];
  if (playerFoundRank <= 100) {
    top100 = allEntries.slice(0, 100);
  } else {
    // If player is just below 100, show top 99 + player as rank 100
    top100 = [...allEntries.slice(0, 99), playerEntry];
  }

  // Next CEO to beat (the one with rank = playerFoundRank - 1)
  let nextCeoToBeat: LeaderboardEntry | null = null;
  let diffToNextRank = 0;
  if (playerFoundRank > 1) {
    const rival = allEntries.find((e) => e.rank === playerFoundRank - 1);
    if (rival) {
      nextCeoToBeat = rival;
      diffToNextRank = Math.max(0, rival.netWorth - playerEntry.netWorth);
    }
  }

  return {
    leaderboard: top100,
    playerEntry,
    playerRank: playerFoundRank,
    totalCeos: 100,
    nextCeoToBeat,
    diffToNextRank,
    top10: top100.slice(0, 10),
  };
}

/**
 * Updates player CEO name in GameState and persists in the offline database.
 */
export function updatePlayerCeoProfile(
  gameState: GameState,
  newCeoName: string,
  newCompanyName?: string
): GameState {
  const updatedName = newCeoName.trim().length > 0 ? newCeoName.trim() : gameState.ceoName;
  const updatedCompany = newCompanyName && newCompanyName.trim().length > 0 ? newCompanyName.trim() : gameState.companyName;

  return {
    ...gameState,
    ceoName: updatedName,
    companyName: updatedCompany,
  };
}

/**
 * Returns formatted JSON export representing the Firebase Realtime Database structure.
 */
export function exportFirebaseRealtimeDbJson(gameState: GameState): string {
  const { leaderboard } = computeTop100Leaderboard(gameState);
  const entriesRecord: Record<string, LeaderboardEntry> = {};
  leaderboard.forEach((entry) => {
    entriesRecord[entry.id] = entry;
  });

  const payload: FirebaseRealtimeLeaderboardNode = {
    ref: RTDB_LEADERBOARD_PATH,
    syncedOffline: true,
    updatedAt: Date.now(),
    entries: entriesRecord,
  };

  return JSON.stringify(payload, null, 2);
}
